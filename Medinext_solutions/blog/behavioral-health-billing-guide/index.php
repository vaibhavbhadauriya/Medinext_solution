                        <h2 id="telehealth" class="fw-bold mb-3 mt-5">2. Mastering Telehealth (Modifier 95 & POS)</h2>
                        <p class="lh-lg mb-4">
                            The catastrophic shift toward digital therapy post-2020 vastly complicated claims. Submitting a telehealth claim using the traditional "in-office" criteria guarantees a brutal denial.
                        </p>
                        <p class="lh-lg mb-4">
                            To assert that the 90834 session occurred digitally, billers must append <strong>Modifier 95</strong> (Synchronous Telemedicine Service Rendered via a Real-Time Interactive Audio and Video Telecommunications System) to the specific CPT line. 
                        </p>
                        <p class="lh-lg mb-4">
                            Furthermore, the Place of Service (POS) code on the CMS-1500 form must be altered. Historically, POS 02 indicated all telehealth. Currently, CMS strictly differentiates: <strong>POS 10</strong> signifies the patient is located in their own home during the call, while <strong>POS 02</strong> indicates the patient is located at a different clinical facility (like a hospital) during the transmission. Interchanging these guarantees a rejection.
                        </p>

