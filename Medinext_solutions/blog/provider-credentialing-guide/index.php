                        <h2 id="what-is" class="fw-bold mb-3 mt-4">1. What is Provider Credentialing?</h2>
                        <p class="lh-lg mb-4">
                            Provider credentialing (often conflated with "payer enrollment") is the grueling, legally mandated process where an insurance company rigorously verifies a physician's education, training, state licensing, and malpractice history. It sits explicitly at the bedrock of your <a href="revenue-cycle-management/" class="text-primary fw-bold text-decoration-none">revenue cycle</a>. 
                        </p>
                        <p class="lh-lg mb-4">
                            If a newly hired surgeon performs $50,000 worth of procedures before their credentialing profile is officially approved by BlueCross BlueShield, BCBS will aggressively deny every single claim as "Out of Network" or "Unrecognized Provider." Unlike missing modifiers, you generally <strong>cannot retro-bill</strong> for dates of service that occurred prior to the official "Effective Date" of the contract.
                        </p>

                        <h2 id="timeline" class="fw-bold mb-3 mt-5">2. The 90-120 Day Timeline Expectation</h2>
                        <p class="lh-lg mb-4">
                            One of the most catastrophic administrative errors a medical practice can make is hiring a physician under the assumption they will be legally "billable" on day one.
                        </p>
                        <ul class="lh-lg mb-4">
                            <li><strong>Phase 1: Application Assembly (Weeks 1-2):</strong> Gathering massive amounts of demographic and educational data, signing rosters, and updating CAQH.</li>
                            <li><strong>Phase 2: Primary Source Verification (Weeks 3-8):</strong> The insurance carrier formally contacts the state medical boards, the DEA, and the provider's medical school to verify the submitted documents are authentic.</li>
                            <li><strong>Phase 3: Committee Review (Weeks 9-12):</strong> The payer?s credentialing committee meets (often merely once per month) to formally vote on adopting the provider into the network.</li>
                            <li><strong>Phase 4: Contract Effective Date (Week 12+):</strong> The network sends the executed contract establishing the precise calendar date the provider may commence billing.</li>
                        </ul>

                        <h2 id="documents" class="fw-bold mb-3 mt-5">3. The 10 Foundational Documents Required</h2>
                        <p class="lh-lg mb-4">
                            Attempting to credential a provider without having an unassailable data cache is futile. Before initializing any application with Aetna, Cigna, or UnitedHealthcare, ensure your <a href="provider-credentialing-services/" class="text-primary fw-bold text-decoration-none">credentialing agency</a> possesses pristine PDF copies of:
                        </p>
                        <ol class="lh-lg mb-5">
                            <li>Current State Medical License(s) covering the exact service geography.</li>
                            <li>Federal DEA Certificate (or respective state-controlled substance licenses).</li>
                            <li>Current Malpractice/Liability Insurance Certificate featuring face-sheet coverage limits.</li>
                            <li>Individual NPI Letter from NPPES (Type 1).</li>
                            <li>Group NPI Letter for the billing entity (Type 2).</li>
                            <li>Board Certification certificates (e.g., ABIM).</li>
                            <li>Medical School Diploma and Residency/Fellowship training certificates.</li>
                            <li>Complete, gap-free Curriculum Vitae (CV) meticulously detailing month-and-year employment.</li>
                            <li>W-9 indicating the precise Tax Identification Number (TIN) for the clinic.</li>
                            <li>Driver's License or valid passport copy.</li>
                        </ol>

