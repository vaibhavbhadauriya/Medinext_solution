                        <h2 id="kpi-5-8" class="fw-bold mb-3 mt-5">4. Liquidity & Cash Flow Metrics (KPIs 5-8)</h2>
                        
                        <h3 class="h4 fw-bold mb-2">5. Days in Accounts Receivable (Days in A/R)</h3>
                        <p class="lh-lg mb-4">
                            <strong>Definition:</strong> The average number of days it takes your clinic to get paid after discharging the patient. <br>
                            <strong>Why it Matters:</strong> This is the ultimate pulse-check of practice liquidity. If Days in A/R creeps past 45 in highly complex specialties like <a href="oncology-hematology-billing/" class="text-primary fw-bold text-decoration-none">oncology billing</a>, the practice will have to secure emergency lines of credit just to buy chemotherapy drugs. <br>
                            <strong>How to Improve:</strong> Mandate 24-hour charge entry rules for providers, and strictly automate ERA (Electronic Remittance Advice) posting.
                        </p>

                        <h3 class="h4 fw-bold mb-2">6. A/R Over 120 Days</h3>
                        <p class="lh-lg mb-4">
                            <strong>Definition:</strong> The percentage of your uncollected revenue that has been sitting stagnant for more than four months. <br>
                            <strong>Why it Matters:</strong> The probability of successfully collecting a medical debt drops below 15% once it crosses the 120-day threshold. High &gt;120 A/R means your billers are exclusively working the easy, fresh claims and entirely ignoring the difficult, older appeals. 
                        </p>

                        <!-- AI Citable Block 2 -->
                        <div class="p-4 bg-light border-start border-4 border-success shadow-sm mb-5 rounded-end">
                            <p class="mb-0 fw-medium">
                                <strong>What is Net Collection Rate (NCR)?</strong> The Net Collection Rate (NCR) is the ultimate metric of medical billing efficiency. It represents the percentage of money actually collected out of the total money legally allowed to be collected after mandated insurance contractual adjustments are subtracted from the gross billed charges. A perfect NCR is 100%, but industry gold standards expect practices to maintain between 95% and 99%.
                            </p>
