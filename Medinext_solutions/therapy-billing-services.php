                        <p>Occupational therapy evaluations require nuanced documentation to justify their tiering (97165 for low complexity, up to 97167 for high complexity). Our <a href="occupational-therapy-billing/">occupational therapy billing</a> team successfully defends these evaluations against payer downcoding. We track the use of therapeutic activities (97530) and self-care management training (97535) using the required GO modifier, ensuring your OT clinic maximizes its lawful revenue.</p>

                        <h3 class="h4 fw-bold mt-4">3. Speech-Language Pathology (ST) Billing</h3>
                        <p>Speech therapy utilizes distinct evaluation and treatment codes that operate differently than PT and OT codes. Our <a href="speech-therapy-billing/">speech therapy billing</a> experts cleanly navigate evaluation codes (92521-92524) and targeted treatments for speech, language, voice, and communication disorders (92507, 92508). We rigorously enforce the use of the GN modifier to indicate services performed under a dedicated speech-language pathology plan.</p>

