                        <h2 class="h3 fw-bold text-primary mt-5 mb-3">2026 Medicaid Suspension vs. Termination</h2>
                        <p>The Consolidated Appropriations Act (CAA) mandated a fundamental shift in how states handle Medicaid for incarcerated individuals. Effective January 1, 2026, <strong>all states are federally prohibited from terminating Medicaid enrollment due to incarceration</strong>; they must instead suspend it.</p>
                        <ul>
                            <li><strong>Off-Site Hospitalizations (The Inpatient Exception)</strong>: While standard Medicaid is suspended, if an inmate requires an off-site inpatient admission lasting 24 hours or more, the suspension is temporarily lifted. We aggressively track these inpatient stays, coordinate with the hospital, and ensure the hospital bills Medicaid rather than the jail, legally shifting hundreds of thousands of dollars off your municipal budget.</li>
                            <li><strong>Rapid Reactivation</strong>: Because coverage is suspended rather than terminated, our systems track release dates to ensure Medicaid is instantly reactivated upon discharge, preventing gaps in care that drive recidivism.</li>
                        </ul>

                        <h2 class="h3 fw-bold text-primary mt-5 mb-3">Section 1115 Reentry Waivers</h2>
                        <p>A growing number of states are actively implementing CMS Section 1115 Reentry Demonstration Waivers. These waivers create a massive new revenue stream for correctional facilities.</p>
                        <p>Under an approved waiver, Medicaid will pay for allowable services (SUD treatment, mental health counseling, MAT, and case management) provided <strong>inside the facility during the 30 to 90 days prior to the inmate's release</strong>. We build the specialized claiming infrastructure required to bill your state Medicaid agency for these pre-release services, turning previously sunk costs into reimbursable revenue.</p>

                        <h2 class="h3 fw-bold text-primary mt-5 mb-3">Third-Party Liability (TPL) and Commercial Insurance</h2>
                        <p>The Inmate Exclusion Policy applies to Medicare and Medicaid, but many commercial insurance policies DO NOT have a strict incarceration exclusion clause, particularly for pretrial detainees who have not yet been convicted.</p>
                        <p>We execute exhaustive insurance discovery on every booked inmate. If a detainee has active commercial health insurance (e.g., through a spouse or employer), we aggressively bill the commercial payer for on-site medical, dental, and behavioral health services before ever passing the cost to the county budget.</p>
