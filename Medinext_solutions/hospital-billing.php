                        <h2 class="h3 fw-bold text-primary mt-5 mb-3">The IPO List Phase-Out and Two-Midnight Rule</h2>
                        <p>The regulatory line between inpatient and outpatient status continues to blur, creating massive compliance and revenue risks.</p>
                        <ul>
                            <li><strong>IPO List Removals</strong>: For 2026, CMS finalized the removal of over <strong>250 musculoskeletal and cardiovascular procedures</strong> from the Inpatient Only (IPO) list. Hospitals can now bill these procedures in the outpatient setting. However, if a patient requires an inpatient stay for one of these procedures, you must rigorously document the medical necessity to survive inevitable MAC/RAC audits.</li>
                            <li><strong>The Two-Midnight Rule</strong>: Medicare strictly enforces the Two-Midnight rule. If the admitting physician expects the patient to require hospital care spanning two or more midnights, the stay is inpatient. If not, it is outpatient/observation. We implement aggressive concurrent CDI to ensure the physician's documented expectation matches the billed status, preventing devastating DRG downcodes.</li>
                        </ul>

                        <h2 class="h3 fw-bold text-primary mt-5 mb-3">Defending Against Site-Neutral Payment Cuts</h2>
                        <p>CMS is aggressively leveling the payment playing field between hospital outpatient departments (HOPDs) and independent physician offices. For 2026, <strong>site-neutral payment cuts have been expanded</strong> to apply to a much broader range of clinic visits and services provided in off-campus HOPDs.</p>
                        <p>If your health system acquires a physician practice and bills their services as an off-campus HOPD (using the PO modifier), you will face significant payment reductions. We help health systems strategically analyze their facility mapping, properly apply the PN (non-excepted) or PO (excepted) modifiers, and optimize their provider-based billing structures to mitigate these cuts where legally permissible.</p>

                        <h2 class="h3 fw-bold text-primary mt-5 mb-3">Charge Description Master (CDM) Integrity</h2>
                        <p>A hospital's revenue cycle lives and dies by the Charge Description Master (CDM). If your chargemaster contains outdated CPT codes, missing revenue codes, or unlinked pharmacy HCPCS codes, claims will fail silently. We perform comprehensive, ongoing CDM maintenance, ensuring every line item is linked to the correct 2026 OPPS status indicators (e.g., J1 for comprehensive APCs, N for packaged services) to prevent revenue leakage at the source.</p>
