                        <p>The 2026 CMS final rule completely restructured how Cellular and/or Tissue-Based Products (CTPs) are reimbursed, ending the era of massive markups on specific product brands.</p>
                        <ul>
                            <li><strong>The New Flat Rate</strong>: CMS has finalized a <strong>flat rate of $127.14 per square centimeter</strong> for all non-BLA (Biologics License Application) skin substitutes. This means your clinic's profitability now relies entirely on efficient inventory management and flawless billing of the exact surface area applied, rather than selecting the highest-priced product.</li>
                            <li><strong>Code Consolidation</strong>: The temporary low-cost HOPD codes (C5271-C5278) have been entirely <strong>deleted for 2026</strong>. Providers in all settings must now use the standard application codes (15271-15278). We ensure your EHR templates and chargemasters are immediately updated to prevent mass denials.</li>
                            <li><strong>Wastage Billing (Modifier JW)</strong>: With the new flat rate, capturing every square centimeter is critical. If a 10 sq cm piece of product is opened but only 6 sq cm is applied to the wound, you must perfectly document and bill the 4 sq cm of wastage using the JW modifier to recover your costs.</li>
                        </ul>

                        <h2 class="h3 fw-bold text-primary mt-5 mb-3">Navigating the New Debridement Rules</h2>
                        <p>The rules for surgical debridement (CPT 11042-11047) underwent a massive structural change for 2026.</p>
                        <p>Previously, coders were taught to code to the "deepest level of tissue removed." <strong>This rule has been REMOVED.</strong> For 2026, you must code based on the type of tissue that constitutes the <em>majority</em> of the debridement by surface area, not just the deepest pinpoint. If a 20 sq cm wound involves 18 sq cm of subcutaneous tissue removal and only a 2 sq cm pinpoint of muscle removal, it must be billed as subcutaneous (11042), not muscle (11043). Our certified coders meticulously analyze your operative reports to ensure compliance with this radical new directive.</p>

                        <h2 class="h3 fw-bold text-primary mt-5 mb-3">Hyper-Specific ICD-10 Coding</h2>
                        <p>Wound care requires the most granular ICD-10 coding in medicine. Denials for "lack of medical necessity" are rampant if the exact etiology (venous, arterial, diabetic), laterality, and anatomical location are not perfectly specified. Furthermore, many LCDs require dual coding: an underlying condition code (e.g., E08.621 for Diabetes with foot ulcer) sequenced before the specific ulcer code (e.g., L97.411 for right heel ulcer with skin breakdown). We train your providers to capture this specificity at the point of care.</p>
