                        <h2 class="h3 fw-bold text-primary mt-5 mb-3">Navigating the OT Evaluation Codes (97165 - 97168)</h2>
                        <p>The transition to tiered evaluation codes severely complicated OT billing. CMS requires therapists to determine the exact complexity of an evaluation based on the patient's occupational profile, the number of performance deficits, and the level of clinical decision-making involved. Billing the wrong tier means leaving money on the table or triggering a federal audit.</p>
                        <ul>
                            <li><strong>97165 (Low Complexity):</strong> Requires an occupational profile and medical history, 1-3 performance deficits relating to physical/cognitive/psychosocial skills, and low clinical decision-making.</li>
                            <li><strong>97166 (Moderate Complexity):</strong> Requires an expanded profile, 3-5 performance deficits, and moderate decision-making with detailed assessments.</li>
                            <li><strong>97167 (High Complexity):</strong> Requires an extensive profile, 5 or more performance deficits, and high clinical decision-making, often involving severe comorbidities.</li>
                            <li><strong>97168 (Re-evaluation):</strong> Used when a documented change in the patient's functional status requires a revised plan of care.</li>
                        </ul>
                        <p>MEDINEXT SOLUTIONS's claim scrubbing software perfectly aligns your clinical documentation with the correct CPT tier, guaranteeing that your evaluations are never arbitrarily downcoded by commercial payers.</p>

                        <h2 class="h3 fw-bold text-primary mt-5 mb-3">Mastering the Core OT Treatment Codes</h2>
                        <p>Once the evaluation is complete, tracking the therapeutic interventions demands precision. We thoroughly manage both timed and untimed therapy codes, ensuring total compliance with the Medicare 8-minute rule:</p>
                        <ul>
                            <li><strong>97530 (Therapeutic Activities):</strong> Direct, one-on-one patient contact utilizing dynamic activities to improve functional performance. This is heavily scrutinized by Medicare to differentiate it from therapeutic exercise (97110). Our coders ensure your notes clearly define the "functional" difference to avoid denials.</li>
                            <li><strong>97535 (Self-Care/Home Management Training):</strong> Activities of Daily Living (ADL) and compensatory training, meal preparation, safety procedures, and instructions in use of assistive technology devices/adaptive equipment.</li>
                            <li><strong>97112 (Neuromuscular Re-education):</strong> Often billed in OT for movement, balance, coordination, kinesthetic sense, posture, and/or proprioception for sitting and/or standing activities.</li>
                            <li><strong>97542 (Wheelchair Management):</strong> Assessment, fitting, and training regarding wheelchair utilization.</li>
                        </ul>

                        <h2 class="h3 fw-bold text-primary mt-5 mb-3">The Essential GO Modifier & Audit Defense</h2>
                        <p>Every claim submitted for occupational therapy must include the <strong>GO modifier</strong>. This alerts Medicare (and most commercial payers) that the service was performed under an established outpatient OT plan of care. Omitting this modifier is the fastest way to get a claim instantly rejected.</p>
