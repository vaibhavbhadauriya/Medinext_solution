                        <h2 class="h3 fw-bold text-primary mt-5 mb-3">Expert CDT Coding for Maximum Reimbursement</h2>
                        <p>CDT codes are updated annually by the American Dental Association, and using outdated or incorrect codes results in immediate claim rejection. Private practices frequently undercode complex procedures or miss bundling opportunities.</p>
                        <ul>
                            <li><strong>Restorative & Prosthodontic Coding</strong>: We ensure crowns (D2740-D2799), bridges (D6200-D6253), and implant restorations (D6058-D6067) are coded with the correct material, tooth number, and surface designations. We apply narrative justifications when payers require clinical rationale for procedures outside frequency limitations.</li>
                            <li><strong>Periodontal Coding Optimization</strong>: Scaling and root planing (D4341/D4342), osseous surgery (D4260/D4261), and periodontal maintenance (D4910 vs. D1110) require precise documentation of pocket depths and clinical attachment loss. We audit your perio charting to ensure coding matches clinical findings, maximizing reimbursement while maintaining audit defensibility.</li>
                            <li><strong>Oral Surgery & Extractions</strong>: Simple (D7140), surgical (D7210), and impacted tooth extractions (D7220-D7240) have vastly different reimbursement rates. We ensure your operative notes support the highest defensible code, and when applicable, cross-bill to medical insurance for trauma or pathology cases.</li>
                        </ul>

