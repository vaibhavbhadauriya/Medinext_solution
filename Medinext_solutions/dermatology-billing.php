                        <h2 class="h3 fw-bold text-primary mt-5 mb-3">Mastering Dermatology CPT Codes</h2>
                        <p>Precision is everything in dermatology coding. Reimbursement is heavily dependent on the exact size, location, and pathology of the lesion treated.</p>

                        <h3 class="h4 fw-bold mt-4">1. Mohs Micrographic Surgery (17311-17315)</h3>
                        <p>Mohs surgery is one of the most profitable, yet heavily audited, procedures in dermatology. The coding is dictated by the anatomic location, the number of stages, and the number of tissue blocks examined.</p>
                        <ul>
                            <li><strong>CPT 17311</strong>: Mohs micrographic technique, including removal of all gross tumor, surgical excision of tissue specimens, mapping, color coding of specimens, microscopic examination... first stage, head, neck, hands, feet, genitalia, or any location with surgery directly involving muscle, cartilage, bone, tendon, major nerves, or vessels.</li>
                            <li><strong>Add-on Codes (17312-17315)</strong>: Proper utilization of add-on codes for additional stages or blocks is critical. We ensure that documentation meticulously maps to the block counts billed to prevent automatic downgrades from Medicare and commercial carriers.</li>
                        </ul>

                        <h3 class="h4 fw-bold mt-4">2. Biopsies and Lesion Excisions</h3>
                        <p>Billing for excisions requires waiting for pathology results to code appropriately, as CPT codes differ fundamentally between benign (11400-11446) and malignant (11600-11646) lesions.</p>
                        <p>Furthermore, new biopsy codes differentiate by technique: tangential (shave) (11102, 11103), punch (11104, 11105), and incisional (11106, 11107). Our coders perfectly align the clinical technique with the primary and add-on biopsy codes, ensuring multiple biopsies on a single date of service are reimbursed fully through the correct application of <strong>Modifier 59</strong> or the X{EPSU} modifiers.</p>

                        <h2 class="h3 fw-bold text-primary mt-5 mb-3">Conquering Modifiers 25 and 59 in Dermatology</h2>
                        <p>The Office of Inspector General (OIG) continuously targets dermatology practices for the overuse of Modifier 25. Insurers will look for any excuse to bundle an E/M visit into a surgical procedure (like a biopsy or cryosurgery).</p>
                        <ul>
                            <li><strong>Modifier 25 Bot Audits</strong>: In 2026, major commercial payers deployed AI-driven "bot audits" that automatically deny Modifier 25 claims when billed with a minor procedure (0-10 day global) unless explicit, separately identifiable diagnosis codes are pointed to the E/M line. We configure your EHR mapping to defeat these algorithmic denials automatically.</li>
                            <li><strong>Modifier 59 / 51</strong>: When excising multiple lesions or performing disparate procedures, we utilize the appropriate unbundling modifiers (or the more specific X{EPSU} modifiers for Medicare) to bypass National Correct Coding Initiative (NCCI) edits, ensuring you are paid for each distinct service rendered.</li>
                        </ul>
                        
                        <h2 class="h3 fw-bold text-primary mt-5 mb-3">Critical 2026 Dermatology CPT Updates</h2>
                        <p>Remaining profitable requires adapting to the latest 2026 CPT revisions and heightened payer scrutiny.</p>
                        <ul>
                            <li><strong>Mohs Surgery Scrutiny (17311-17315)</strong>: While the core Mohs codes remain unchanged for 2026, CMS has categorized them as "High Target" for retrospective audits. We enforce strict documentation templates ensuring your operative notes mathematically match the exact number of stages and blocks billed.</li>
                            <li><strong>CPT 10040 Revised</strong>: The code for acne surgery (10040) has undergone a major revision regarding the definition of "extensive." Billing this code now requires specific documentation of the number of lesions extracted and the time spent, differentiating it from a standard E/M service. We ensure your providers meet this new threshold.</li>
                        </ul>

                        <h2 class="h3 fw-bold text-primary mt-5 mb-3">Dermatopathology and Lab Billing</h2>
                        <p>Many dermatology practices operate in-house CLIA-certified labs. Managing the TC (Technical Component) and 26 (Professional Component) splits for dermatopathology (e.g., CPT 88304, 88305) is complex. We manage the delicate balance of global lab billing versus split billing depending on your specific payer contracts and lab setup, capturing maximum value for your slide interpretations.</p>
